export interface TsumuraMonograph {
  number: string;
  name: string;
  indication: string;
  aliases: string[];
  title: string;
  url: string;
  /** Known base formulas for matching prior use; does not imply dose equivalence. */
  combinationParts?: string[];
}

function monograph(
  number: string,
  name: string,
  indication: string,
  aliases: string[],
  combinationParts?: string[],
): TsumuraMonograph {
  return {
    number,
    name,
    indication,
    aliases,
    title: `쯔무라 TJ-${number} ${name} · 의료용 제제 설명서`,
    url: `https://www.tsumura.co.jp/products/item/${number.padStart(3, '0')}.pdf`,
    ...(combinationParts ? { combinationParts } : {}),
  };
}

